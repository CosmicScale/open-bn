#!/usr/bin/env python3
"""Generate src/scene/cloud_noise.inc: the initializer of `s_noise` (src/scene/cloud.cpp).

The 4096-byte 1D noise table of the original (`.data` at 0x100B4B08) is not an
asset: it comes from a closed formula, a sum of sines over 11 octaves
(frequency 2^k, amplitude 1/2^k), normalized min..max -> 0..255 and truncated
(4096/4096 bytes equal, in double and in float32; 10 octaves or *256 instead
of *255 do not match). Like tif_fax3sm.c (generated by mkg3states) the table is
written from the generator, not from the ELF bytes.

    python3 tools/gen_cloud_noise.py            # rewrite src/scene/cloud_noise.inc
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'scene', 'cloud_noise.inc')
N = 4096
OCTAVES = 11


def generate():
    s = []
    for i in range(N):
        v = 0.0
        for k in range(OCTAVES):
            v += math.sin(2.0 * math.pi * (1 << k) * i / N) / (1 << k)
        s.append(v)
    mn, mx = min(s), max(s)
    return bytes(int((v - mn) / (mx - mn) * 255.0) for v in s)


def main():
    t = generate()
    lines = ['/* GENERATED by tools/gen_cloud_noise.py: do not edit by hand.',
             '   s_noise of src/scene/cloud.cpp: 1D noise, sum of sines over 11 octaves',
             '   (2^k, 1/2^k) normalized to 0..255. */']
    for r in range(0, N, 16):
        lines.append(' ' + ', '.join(str(x) for x in t[r:r + 16]) + ',')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(f'wrote {os.path.relpath(OUT, ROOT)} ({N} values)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
